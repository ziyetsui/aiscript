import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { unzipSync, strFromU8 } from 'fflate';
import { _electron as electron } from 'playwright-core';
import { generateKeypair, issueOfflineCode } from '../../../packages/license/src/offline.ts';
import { GOOD_KEY, startFakeAncher } from './fake-ancher.ts';

const tmp = mkdtempSync(join(tmpdir(), 'scripter-revisions-'));
const fake = await startFakeAncher();
const { privatePem, publicPem } = generateKeypair(); writeFileSync(join(tmp, 'pub.pem'), publicPem);
const env = { ...process.env, SCRIPTER_E2E: '1', SCRIPTER_USER_DATA: join(tmp, 'data'), SCRIPTER_LICENSE_PUBKEY: join(tmp, 'pub.pem'), SCRIPTER_ANCHER_BASE_URL: fake.url };
const evidence = join(import.meta.dirname, '../../../delivery/evidence'); mkdirSync(evidence, { recursive: true });
let app = await electron.launch({ args: [join(import.meta.dirname, '..')], env, colorScheme: null as never });
let page = await app.firstWindow(); page.setDefaultTimeout(15000);
try {
  await page.locator('.mc .tnum').waitFor();
  const machine = (await page.locator('.mc .tnum').textContent())!.trim();
  await page.locator('#code').fill(issueOfflineCode(privatePem, { mid: machine, cust: '版本验证', seat: '1/1', exp: null }));
  await page.getByRole('button', { name: '激活', exact: true }).click();
  await page.locator('#k-ancher').fill(GOOD_KEY); await page.getByRole('button', { name: '验证并保存' }).click(); await page.locator('#ask').waitFor();
  const seeded = await page.evaluate(async () => {
    const p = await window.api.projects.create('版本控制验证', 'script');
    await window.api.projects.edit(p.id, [{ op: 'insert', after: 'end', type: 'heading', text: '内景 书房 — 日', id: 'scene1' }, { op: 'insert', after: 'end', type: 'action', text: '第一稿：孩子认真画画。', id: 'action1' }]);
    const versions = await window.api.projects.revisions(p.id, 'first');
    const other = await window.api.projects.episode(p.id, 'create', undefined, '第二集');
    const otherId = other.activeEpisodeId;
    await window.api.projects.edit(p.id, [{ op: 'insert', after: 'end', type: 'action', text: '另一集不应该改变。', id: 'other1' }]);
    await window.api.projects.episode(p.id, 'select', 'first');
    await window.api.projects.setOutline(p.id, '当前大纲不应该改变');
    await window.api.projects.edit(p.id, [{ op: 'text', id: 'action1', text: '第二稿：孩子开始练习舞步。' }]);
    await window.api.projects.revisions(p.id, 'first');
    return { id: p.id, revision: versions[0]!.revision, otherId };
  });
  await page.getByRole('button', { name: '最近项目', exact: true }).click();
  await page.getByRole('button', { name: '版本控制验证', exact: true }).click();
  await page.locator('.paper [data-id="action1"]').waitFor();
  await page.getByRole('button', { name: '剧本版本历史', exact: true }).click();
  const choice = page.getByRole('menuitem', { name: `预览 v${seeded.revision}`, exact: true }); await choice.waitFor(); await choice.click();
  await page.getByRole('region', { name: '历史版本预览' }).waitFor();
  assert.match((await page.locator('.revision-paper').innerText()), /第一稿/);
  assert.equal(await page.locator('.revision-paper [contenteditable]').count(), 0);
  assert.equal(await page.getByRole('toolbar', { name: '剧本格式' }).count(), 0);
  assert.match(await page.evaluate(async id => (await window.api.projects.open(id)).nodes.find(n => n.id === 'action1')!.text, seeded.id), /第二稿/);
  await page.screenshot({ path: join(evidence, 'script-revision-preview-light.png') });
  await page.getByRole('button', { name: '返回当前版本', exact: true }).click();
  assert.match(await page.locator('.paper [data-id="action1"]').innerText(), /第二稿/);
  await page.getByRole('button', { name: '剧本版本历史', exact: true }).click();
  await page.getByRole('menuitem', { name: '保存当前版本', exact: true }).click();
  await page.getByText('已保存剧本版本', { exact: true }).waitFor();
  await page.getByRole('button', { name: '剧本版本历史', exact: true }).click();
  await page.getByRole('menu', { name: '剧本版本', exact: true }).waitFor();
  assert.equal(await page.locator('.revision-menu').evaluate(el => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), true, 'Version menu must not be clipped by the scrolling topbar');
  await page.screenshot({ path: join(evidence, 'script-revision-picker-light.png'), animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.getByRole('menu', { name: '剧本版本', exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '剧本版本历史', exact: true }).click();
  await page.getByRole('menuitem', { name: `预览 v${seeded.revision}`, exact: true }).click();
  // Make only the portable mirror unwritable; the authoritative SQLite commit must still win.
  const projectDir = join(tmp, 'data', 'projects', seeded.id);
  rmSync(join(projectDir, 'script.loro')); mkdirSync(join(projectDir, 'script.loro'));
  await page.getByRole('button', { name: '恢复为当前', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.paper [data-id="action1"]')?.textContent?.includes('第一稿'));
  const checked = await page.evaluate(async s => {
    const state = await window.api.projects.open(s.id);
    const versions = await window.api.projects.revisions(s.id, 'first');
    const before = await window.api.projects.revision(s.id, 'first', versions[1]!.revision);
    await window.api.projects.episode(s.id, 'select', s.otherId);
    const other = await window.api.projects.open(s.id);
    await window.api.projects.episode(s.id, 'select', 'first');
    let rejected = false;
    try { await window.api.projects.restoreRevision(s.id, s.otherId, 1); } catch { rejected = true; }
    return { outline: state.outline, before: before.nodes.find(n => n.id === 'action1')!.text, other: other.nodes[0]!.text, rejected, count: versions.length, latest: versions[0]!.revision };
  }, seeded);
  assert.equal(checked.outline, '当前大纲不应该改变'); assert.match(checked.before, /第二稿/); assert.equal(checked.other, '另一集不应该改变。'); assert.equal(checked.rejected, true);
  const archivePath = join(tmp, 'versions.scripter');
  await app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = (async () => ({ canceled: false, filePath: path })) as typeof dialog.showSaveDialog; dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [path] })) as typeof dialog.showOpenDialog; }, archivePath);
  const exported = await page.evaluate(async id => window.api.projects.exportArchive(id), seeded.id); assert.equal(exported.ok, true);
  const zip = unzipSync(new Uint8Array(readFileSync(archivePath))); const history = JSON.parse(strFromU8(zip['script-revisions.json']!)); assert.ok(history.length >= checked.count);
  rmSync(join(projectDir, 'script.loro'), { recursive: true });
  const recovered = await page.evaluate(async id => {
    const name = await window.api.localData.backup(id);
    const restored = await window.api.localData.recover(id, name);
    return { state: await window.api.projects.open(restored.id), versions: await window.api.projects.revisions(restored.id, 'first') };
  }, seeded.id);
  assert.match(recovered.state.nodes.find(n => n.id === 'action1')!.text, /第一稿/);
  assert.equal(recovered.versions.length, checked.count);
  const imported = await page.evaluate(async () => window.api.projects.importArchive()); assert.ok(imported);
  assert.equal(await page.evaluate(async id => (await window.api.projects.revisions(id, 'first')).length, imported!.id), checked.count);
  await page.evaluate(async () => window.api.app.setTheme('dark'));
  await page.getByRole('button', { name: '剧本版本历史', exact: true }).click();
  await page.getByRole('menu', { name: '剧本版本', exact: true }).waitFor();
  await page.screenshot({ path: join(evidence, 'script-revision-picker-dark.png'), animations: 'disabled' });
  await page.keyboard.press('Escape');
  await app.close();
  app = await electron.launch({ args: [join(import.meta.dirname, '..')], env, colorScheme: null as never }); page = await app.firstWindow();
  await page.getByRole('button', { name: '最近项目', exact: true }).waitFor();
  const after = await page.evaluate(async id => ({ state: await window.api.projects.open(id), versions: await window.api.projects.revisions(id, 'first') }), seeded.id);
  assert.match(after.state.nodes.find(n => n.id === 'action1')!.text, /第一稿/); assert.equal(after.versions.length, checked.count); assert.equal(after.versions[0]!.revision, checked.latest);
  console.log('Script revisions E2E passed: read-only preview, current draft preserved, manual save, safe restore, episode isolation, archive roundtrip, restart persistence, light/dark screenshots.');
} finally { await app.close(); fake.server.close(); rmSync(tmp, { recursive: true, force: true }); }
